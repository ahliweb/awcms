#!/usr/bin/env bun
/**
 * jobs:env-allowlist — render the set of environment variables a scheduled job
 * container must receive, from the variables the code ACTUALLY reads.
 *
 * ## Why this exists
 *
 * `ops/run-job.sh` copies env out of the running app container and into the job
 * container. It used to select what to copy with a hand-maintained prefix
 * pattern:
 *
 *     grep -E '^(DATABASE_URL|WORKER_DATABASE_URL|…|CLOUDFLARE_|EDGE_CACHE_)'
 *
 * Measured against `collectEnvReads()` at the time this landed, that pattern
 * dropped **81 of the 171** variables this codebase reads. Not ten. Among them:
 *
 * - `DATA_LIFECYCLE_ARCHIVE_ROOT_PATH` and `REPORTING_EXPORT_ROOT_PATH` — the
 *   two paths that decide WHERE a job writes the artefact a database row then
 *   claims exists;
 * - every `TENANT_DOMAIN_CLOUDFLARE_*` variable, because `^CLOUDFLARE_` is
 *   anchored and those do not start with it — so `tenant-domain:dns:sync` ran
 *   with no API token and no zone;
 * - every `VISITOR_ANALYTICS_*` variable, including the retention windows that
 *   `analytics:purge` exists to enforce;
 * - `SYNC_HMAC_ALLOW_LEGACY`, `SITE_SEARCH_*`, `TURNSTILE_*`, `TRUSTED_PROXY_*`.
 *
 * A job missing a variable does not fail. It takes the code's default, which is
 * usually the safe-but-inert one, and reports success — the shape this repo has
 * shipped before and keeps finding.
 *
 * ## Why a generated allow-list and not a deny-list
 *
 * The file lands on a host and is read into a `0600` temp file, so what it names
 * is worth bounding. But the bound must not be a hand-kept guess: the failure
 * that matters here is a variable MISSING, and a hand-kept pattern goes stale on
 * the day somebody adds one. Generating it from the same source
 * `config:env:coverage:check` uses means the list cannot fall behind the code
 * without a gate going red.
 *
 * `TOOLING_ONLY` names are excluded: they belong to build/CI tooling and no job
 * process reads them, which is the same reason the coverage gate exempts them.
 *
 * ## What the generator can and cannot see (Issue #1119)
 *
 * `collectEnvReads()` resolves `process.env.X`, `process.env["X"]`, and every
 * identifier bound to the environment — by initialiser (`const env =
 * process.env`) or by TYPE (`env: NodeJS.ProcessEnv`, with or without a
 * default) — read as `env.X`, `env?.X`, `env["X"]` or `const { X } = env`. It
 * cannot see a computed name; those live in `COMPUTED_ENV_READS` beside the
 * scanner. Before #1119 a function that merely RECEIVED the environment was
 * invisible, which is how the three `PUSH_VAPID_*` variables never reached
 * `push:dispatch`: the host started the dispatcher with push enabled and no
 * VAPID material.
 *
 * ## Job-scoped secrets (Issue #1120)
 *
 * One global list means every secret on it reaches EVERY job container (~40 of
 * them), though only a few jobs read most of them. After #1119 that included
 * `PUSH_VAPID_PRIVATE_KEY` and `TELEGRAM_CHAT_HASH_KEYS`. `JOB_SCOPED` below is
 * an explicit map `secret -> the job targets that may receive it`, each with a
 * reason. The generator therefore writes TWO files:
 *
 * - `ops/awcms-jobs.env-global`    — the global list MINUS the scoped and web-only names;
 * - `ops/awcms-jobs.env-scoped`    — one `<job-target> <VAR>` line per grant.
 *
 * `ops/run-job.sh` copies the global names plus the scoped names whose job
 * equals `$1` (exact match), and refuses to run when either file is missing.
 *
 * The map is explicit rather than derived from an import graph on purpose: a
 * derivation that misses an edge makes a job fail SILENTLY (it sees the secret
 * as unset and takes the inert default). The map is instead HELD to the import
 * graph by a test (`tests/jobs-env-scoped-reach.test.ts`, using
 * `scripts/lib/job-import-graph.ts`) in both directions: a job that can reach a
 * file reading a scoped secret must be granted it, and a granted job must really
 * reach a reader. Only secrets belong in the map; non-secret configuration stays
 * global, because a surplus number costs nothing and a missed one costs a silent
 * misconfiguration.
 *
 * Usage:
 *   bun run jobs:env-allowlist:generate
 *   bun run jobs:env-allowlist:check
 */
