/** Names in the global list that look like secrets and have no entry in `GLOBAL_SECRETS`. */
export function findUnexplainedGlobalSecrets(
  globalNames: readonly string[]
): string[] {
  const explained = new Set(GLOBAL_SECRETS.map((entry) => entry.name));
  return globalNames.filter(
    (name) => SECRET_NAME_PATTERN.test(name) && !explained.has(name)
  );
}

/** Mistakes in `GLOBAL_SECRETS` itself: an entry that is no longer global, or has no reason. */
export function validateGlobalSecrets(
  globalNames: readonly string[]
): string[] {
  const present = new Set(globalNames);
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const entry of GLOBAL_SECRETS) {
    if (seen.has(entry.name)) problems.push(`${entry.name}: listed twice.`);
    seen.add(entry.name);
    if (!present.has(entry.name)) {
      problems.push(
        `${entry.name}: in GLOBAL_SECRETS but not in the global list (scoped, web-only or no longer read) - remove the stale entry.`
      );
    }
    if (entry.reason.trim().length < 20) {
      problems.push(`${entry.name}: needs a reason.`);
    }
  }
  return problems;
}

/** Every (job, variable) grant in `JOB_SCOPED`, sorted by job then variable. */
export function scopedPairs(): { job: string; name: string }[] {
  return JOB_SCOPED.flatMap((secret) =>
    secret.jobs.map((job) => ({ job: job.target, name: secret.name }))
  ).sort((a, b) =>
    a.job === b.job ? (a.name < b.name ? -1 : 1) : a.job < b.job ? -1 : 1
  );
}

/** Mistakes in the maps themselves, independent of the code. */
export function validateJobScoped(
  reads: ReadonlyMap<string, string[]>
): string[] {
  const problems: string[] = [];
  const webOnly = new Set(WEB_ONLY.map((entry) => entry.name));
  const seenNames = new Set<string>();

  for (const secret of JOB_SCOPED) {
    if (seenNames.has(secret.name)) {
      problems.push(`${secret.name}: listed twice in JOB_SCOPED.`);
    }
    seenNames.add(secret.name);

    if (!reads.has(secret.name)) {
      problems.push(
        `${secret.name}: in JOB_SCOPED but no source reads it, so the entry is stale.`
      );
    }
    if (webOnly.has(secret.name)) {
      problems.push(
        `${secret.name}: in both JOB_SCOPED and WEB_ONLY, so it would reach no job at all.`
      );
    }
    if (secret.reason.trim().length < 20 || secret.jobs.length === 0) {
      problems.push(`${secret.name}: needs a reason and at least one job.`);
    }

    const targets = new Set<string>();
    for (const job of secret.jobs) {
      if (targets.has(job.target)) {
        problems.push(`${secret.name}: ${job.target} listed twice.`);
      }
      targets.add(job.target);
      if (job.target.length === 0 || /\s/.test(job.target)) {
        problems.push(
          `${secret.name}: job target "${job.target}" must be a bare bun-run target (the scoped file is whitespace-separated).`
        );
      }
      if (job.reason.trim().length < 10) {
        problems.push(`${secret.name}: ${job.target} has no reason.`);
      }
    }
  }

  return problems;
}

/** Names in the GLOBAL list: everything read, minus tooling-only, web-only and job-scoped. */
export async function collectJobEnvNames(): Promise<string[]> {
  const reads = await collectEnvReads();
  const toolingOnly = new Set(TOOLING_ONLY.map((entry) => entry.name));
  const webOnly = new Set(WEB_ONLY.map((entry) => entry.name));
  const scoped = new Set(JOB_SCOPED.map((entry) => entry.name));

  return [...reads.keys()]
    .filter(
      (name) =>
        !toolingOnly.has(name) && !webOnly.has(name) && !scoped.has(name)
    )
    .sort();
}

function readIfPresent(file: string): string | null {
  try {
    return readFileSync(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    return null;
  }
}

async function main(): Promise<void> {
  const problems = validateJobScoped(await collectEnvReads());
  if (problems.length > 0) {
    console.error(
      `jobs:env-allowlist FAILED — JOB_SCOPED is inconsistent:\n  ${problems.join("\n  ")}`
    );
    process.exit(1);
  }

  const names = await collectJobEnvNames();
  const pairs = scopedPairs();

  // The secret-name gate (Issue #1120, M2): anything still in the GLOBAL list
  // that looks like a secret reaches every job container, so it has to be
  // explained or moved.
  const unexplained = findUnexplainedGlobalSecrets(names);
  const globalProblems = [
    ...unexplained.map(
      (name) =>
        `${name}: looks like a secret and is in the global list. Add it to JOB_SCOPED (jobs that read it), WEB_ONLY (no job reads it), or GLOBAL_SECRETS with a reason.`
    ),
    ...validateGlobalSecrets(names)
  ];
  if (globalProblems.length > 0) {
    console.error(
      `jobs:env-allowlist FAILED — the global list hands a secret to every job:\n  ${globalProblems.join("\n  ")}`
    );
    process.exit(1);
  }

  // A generator that walks nothing renders an EMPTY allow-list, and an empty
  // allow-list makes every job run with no database URL — a failure that looks
  // like an outage rather than like a broken generator. This repo has shipped a
  // gate that passed while scanning zero files; it does not need a generator
  // that ships zero lines.
  if (names.length < 50) {
    console.error(
      `jobs:env-allowlist FAILED — only ${names.length} environment variable(s) found. ` +
        "Run this from the repository root; a near-empty allow-list would strip a job's " +
        "entire configuration and the job would still report success."
    );
    process.exit(1);
  }

  const runnerSource = readIfPresent(path.join(ROOT, RUNNER));
  const runnerRendered =
    runnerSource === null
      ? null
      : spliceRunnerRefusal(
          runnerSource,
          renderRunnerRefusal(
            OPERATOR_ONLY_TARGETS.map((entry) => entry.target)
          )
        );
  if (runnerRendered === null) {
    console.error(
      `jobs:env-allowlist FAILED — ${RUNNER} is missing or lacks the generated block between\n  ${RUNNER_BEGIN}\n  ${RUNNER_END}\n` +
        "  Without it the runner would run operator-only commands in a job container."
    );
    process.exit(1);
  }

  const fingerprint = envFingerprint(names, pairs);
  const outputs = [
    { file: OUTPUT, rendered: renderGlobal(names, fingerprint) },
    { file: SCOPED_OUTPUT, rendered: renderScoped(pairs, fingerprint) },
    { file: RUNNER, rendered: runnerRendered }
  ];

  if (CHECK_ONLY) {
    const stale = outputs.filter(
      (output) =>
        readIfPresent(path.join(ROOT, output.file)) !== output.rendered
    );

    if (stale.length > 0) {
      for (const output of stale) {
        const missing = readIfPresent(path.join(ROOT, output.file)) === null;
        console.error(
          `jobs:env-allowlist:check FAILED — ${output.file} is ${missing ? "missing" : "stale"}.`
        );
      }
      console.error(
        "  Run `bun run jobs:env-allowlist:generate` and commit the result.\n" +
          "  A stale list means a scheduled job runs without a variable it reads,\n" +
          "  takes the default, and reports success."
      );
      process.exit(1);
    }

    console.log(
      `jobs:env-allowlist:check OK — ${OUTPUT} names ${names.length} variable(s) and ${SCOPED_OUTPUT} ` +
        `holds ${pairs.length} job-scoped grant(s); ${RUNNER} refuses ${OPERATOR_ONLY_TARGETS.length} operator-only target(s); all match a fresh regeneration.`
    );
  } else {
    for (const output of outputs) {
      writeFileSync(path.join(ROOT, output.file), output.rendered);
    }
    console.log(
      `jobs:env-allowlist — wrote ${OUTPUT} (${names.length} variable(s)), ${SCOPED_OUTPUT} (${pairs.length} grant(s)) and the operator-only refusal in ${RUNNER} (${OPERATOR_ONLY_TARGETS.length} target(s)).`
    );
  }
}

if (import.meta.main) {
  await main();
}
