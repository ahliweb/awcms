/**
 * The installable-admin contract (Issue #1105): ONE origin-level web app
 * manifest for the `/admin/` surface, so an iPhone/iPad (iOS/iPadOS 16.4+) can
 * "Add to Home Screen" as a standalone web app -- the precondition for Web Push
 * to be delivered by the existing `push_delivery` sender (ADR-0074).
 *
 * ## Why ONE manifest, identified by the ORIGIN
 *
 * An installed web app is keyed by origin + manifest `id`. The `id` here is the
 * fixed path `/admin/`, so it resolves to `<origin>/admin/` on every
 * deployment: stable across releases and across name/colour edits, and unable
 * to collide between tenants because tenants do not share an origin unless they
 * share this one admin. The name and colours come from DEPLOYMENT config
 * (`PWA_*`), never from the `Host` header and never from a tenant row: a
 * manifest derived from the request would make the installed identity depend on
 * whichever hostname the visitor happened to type, and would let a spoofed
 * `Host` mint an app identity.
 *
 * Per-tenant manifests are out of scope. If a deployment ever serves several
 * tenants from separate verified origins (`tenant_domain`), the safe extension
 * is to resolve the tenant from the VERIFIED primary domain -- the way
 * `robots.txt` does -- and keep `id` per origin. That is a separate issue.
 *
 * ## What is deliberately NOT here
 *
 * No service worker is declared by the manifest and no `serviceworker` member
 * exists: `public/push-sw.js` keeps its fixed path and its default scope, and is
 * registered only from the push enrolment gesture. Installability on iOS does
 * not need a worker, and adding one for the admin shell would be a second
 * registration with its own caching semantics.
 */

/** The admin route prefix (`PROTECTED_PREFIX` in `src/middleware.ts`) + slash. */
export const ADMIN_SCOPE = "/admin/";
export const ADMIN_START_URL = "/admin/";
/** Stable installed-app identity. NEVER derive this from configuration. */
export const WEB_APP_MANIFEST_ID = "/admin/";
export const WEB_APP_MANIFEST_PATH = "/manifest.webmanifest";

export const APPLE_TOUCH_ICON_PATH = "/icons/apple-touch-icon.png";

export const DEFAULT_PWA_APP_NAME = "AWCMS Admin";
export const DEFAULT_PWA_SHORT_NAME = "AWCMS";
/** `--color-primary` in `src/styles/tokens.css`. */
export const DEFAULT_PWA_THEME_COLOR = "#2563eb";
export const DEFAULT_PWA_BACKGROUND_COLOR = "#ffffff";

/** Self-hosted, generated by `bun run pwa:icons:generate`. */
export const PWA_ICONS = Object.freeze([
  {
    src: "/icons/icon-192.png",
    sizes: "192x192",
    type: "image/png",
    purpose: "any"
  },
  {
    src: "/icons/icon-512.png",
    sizes: "512x512",
    type: "image/png",
    purpose: "any"
  },
  {
    src: "/icons/icon-maskable-512.png",
    sizes: "512x512",
    type: "image/png",
    purpose: "maskable"
  }
] as const);

export interface PwaIdentity {
  name: string;
  shortName: string;
  themeColor: string;
  backgroundColor: string;
}

const HEX_COLOR = /^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/;

function cleanText(
  value: string | undefined,
  fallback: string,
  max: number
): string {
  // Control (Cc), format (Cf: bidi overrides, zero-width) characters out, then
  // truncation by CODE POINT so a surrogate pair is never split. The value lands
  // in JSON and in an HTML attribute.
  const trimmed = (value ?? "").replace(/[\p{Cc}\p{Cf}]/gu, "").trim();

  return trimmed === "" ? fallback : Array.from(trimmed).slice(0, max).join("");
}

function cleanColor(value: string | undefined, fallback: string): string {
  const trimmed = (value ?? "").trim();

  return HEX_COLOR.test(trimmed) ? trimmed : fallback;
}

/**
 * Deployment branding for the installed app. An invalid value falls back to the
 * default rather than throwing: a typo in a colour must not take the admin
 * shell's `<head>` down.
 */
export function resolvePwaIdentity(
  env: Readonly<Record<string, string | undefined>>
): PwaIdentity {
  return {
    name: cleanText(env.PWA_APP_NAME, DEFAULT_PWA_APP_NAME, 45),
    shortName: cleanText(env.PWA_APP_SHORT_NAME, DEFAULT_PWA_SHORT_NAME, 12),
    themeColor: cleanColor(env.PWA_THEME_COLOR, DEFAULT_PWA_THEME_COLOR),
    backgroundColor: cleanColor(
      env.PWA_BACKGROUND_COLOR,
      DEFAULT_PWA_BACKGROUND_COLOR
    )
  };
}

export function buildWebAppManifest(identity: PwaIdentity) {
  return {
    id: WEB_APP_MANIFEST_ID,
    name: identity.name,
    short_name: identity.shortName,
    start_url: ADMIN_START_URL,
    scope: ADMIN_SCOPE,
    display: "standalone",
    theme_color: identity.themeColor,
    background_color: identity.backgroundColor,
    icons: PWA_ICONS.map((icon) => ({ ...icon }))
  };
}
